import pandas as pd
from pathlib import Path

# ==========================================
# Load Soil Dataset (Only Once)
# ==========================================

BASE_DIR = Path(__file__).resolve().parent.parent.parent

CSV_PATH = BASE_DIR / "data" / "state_soil_data.csv"

print("Soil CSV:", CSV_PATH)
print("Exists:", CSV_PATH.exists())

soil_df = pd.read_csv(CSV_PATH)

# Remove extra spaces from state names
soil_df["state"] = soil_df["state"].astype(str).str.strip()

# ==========================================
# Soil Health Calculator
# ==========================================

def calculate_soil_health(N, P, K, pH):

    score = 0

    # Nitrogen
    if 50 <= N <= 120:
        score += 1

    # Phosphorus
    if 20 <= P <= 60:
        score += 1

    # Potassium
    if 20 <= K <= 80:
        score += 1

    # pH
    if 6.0 <= pH <= 7.5:
        score += 1

    if score == 4:
        return "Excellent"

    elif score == 3:
        return "Good"

    elif score == 2:
        return "Average"

    return "Poor"


# ==========================================
# Fetch Soil Data by State
# ==========================================

def get_soil_data(state: str):

    state = state.strip()

    state_data = soil_df[
        soil_df["state"].str.lower() == state.lower()
    ]

    # --------------------------------------
    # If state is not found
    # --------------------------------------

    if state_data.empty:

        print(f"State '{state}' not found. Using average values.")

        avg = soil_df.mean(numeric_only=True)

        N = round(float(avg["N"]), 2)
        P = round(float(avg["P"]), 2)
        K = round(float(avg["K"]), 2)
        pH = round(float(avg["pH"]), 2)

    else:

        N = round(state_data["N"].mean(), 2)
        P = round(state_data["P"].mean(), 2)
        K = round(state_data["K"].mean(), 2)
        pH = round(state_data["pH"].mean(), 2)

    soil_health = calculate_soil_health(
        N,
        P,
        K,
        pH
    )

    return {

    "N": float(N),

    "P": float(P),

    "K": float(K),

    "pH": float(pH),

    "soil_health": soil_health,

    "recommended_crop": "Not Available",

    "recommendation": "AI recommendation will be generated by Gemini."

}